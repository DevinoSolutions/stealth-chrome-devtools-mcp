"""
Dynamic Hook System - AI-Generated Request Hooks

This system allows AI to create custom hook functions that process network requests
in real-time with no pending state. Hooks are Python functions generated by AI
that can modify, block, redirect, or fulfill requests dynamically.

**This is host Python execution, not a sandbox (T-6206, F-L).** A hook's
``function_code`` is ``exec``'d and a ``custom_condition`` is ``eval``'d in the
backend process, with that process's privileges. The trimmed ``__builtins__``
dicts below only keep the usual hook vocabulary at hand; they are NOT a security
boundary and must not be read as one — the injected ``fnmatch`` module alone
reaches ``os`` (``fnmatch.os``), and ``str.__class__.__base__.__subclasses__()``
works in the eval namespace. Whoever can create a hook can run arbitrary Python
on the host. Do not build a sandbox here by adding names to or removing names
from those dicts; a real boundary would be a separate process.
"""

import asyncio
import fnmatch
import uuid
from collections.abc import Callable
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from typing import Any

import nodriver as uc
from nodriver.core.connection import ProtocolException
from websockets.exceptions import ConnectionClosed, InvalidMessage

from stealth_chrome_devtools_mcp.embedded.debug_logger import debug_logger
from stealth_chrome_devtools_mcp.embedded.tab_close import (
    is_already_gone,
    session_gone,
    target_socket_gone,
)


def gone_reason(error: BaseException) -> str | None:
    """T-8944: why *error* only says a paused request can no longer be resumed.

    Chrome forgets a paused request when its page navigates away, its tab or
    browser closes, or something else already resolved it; the next ``Fetch``
    command for it then fails with ``Invalid InterceptionId`` (-32602), or, when
    nodriver re-opens the closed tab's socket first, with a refused/rejected
    connection. Sending the same command again cannot succeed, and nothing is
    stuck, so the callers log it at WARNING (a breadcrumb) and not as an
    exception event. ``None`` means a real failure.

    The socket cases are the ones Sentry shows and no wider: a ``ConnectionError``
    (WinError 1225 is a ``ConnectionRefusedError`` on Windows),
    ``tab_close.target_socket_gone`` (an ``InvalidStatus`` with HTTP 500, the one
    predicate for it), ``ConnectionClosed`` and ``InvalidMessage``. A timeout, a
    missing file or a 403/404 says nothing about the request, so those stay
    errors and the caller still continues it. A target or session Chrome says it
    no longer has is ``tab_close.is_already_gone`` / ``session_gone``; the latter
    holds here because these commands go through the tab's own session.
    """
    if isinstance(error, ProtocolException) and "Invalid InterceptionId" in str(error):
        return "the interception id is stale (request resolved or page navigated away)"
    if is_already_gone(error) or session_gone(error):
        return "the target or session is gone (tab closed)"
    if isinstance(
        error, (ConnectionError, ConnectionClosed, InvalidMessage)
    ) or target_socket_gone(error):
        return "the tab's socket is gone (tab or browser closed)"
    return None


@dataclass
class RequestInfo:
    """Request information passed to hook functions."""

    request_id: str
    instance_id: str
    url: str
    method: str
    headers: dict[str, str]
    post_data: str | None = None
    resource_type: str | None = None
    stage: str = "request"  # "request" or "response"

    def to_dict(self) -> dict[str, Any]:
        """Convert to dictionary for AI function processing."""
        return asdict(self)


@dataclass
class HookAction:
    """Action returned by hook functions."""

    action: str  # "continue", "block", "redirect", "fulfill", "modify"
    url: str | None = None  # For redirect/modify
    method: str | None = None  # For modify
    headers: dict[str, str] | None = None  # For modify/fulfill
    body: str | None = None  # For fulfill
    status_code: int | None = None  # For fulfill
    post_data: str | None = None  # For modify


class DynamicHook:
    """A dynamic hook with AI-generated function."""

    def __init__(
        self,
        hook_id: str,
        name: str,
        requirements: dict[str, Any],
        function_code: str,
        priority: int = 100,
    ):
        self.hook_id = hook_id
        self.name = name
        self.requirements = requirements
        self.function_code = function_code
        self.priority = priority  # Lower number = higher priority
        self.created_at = datetime.now(tz=timezone.utc)
        self.trigger_count = 0
        self.last_triggered: datetime | None = None
        self.status = "active"
        self.request_stage = requirements.get(
            "stage", "request"
        )  # 'request' or 'response'

        self._compiled_function = self._compile_function()

    def _compile_function(self) -> Callable:
        """Compile the AI-generated function."""
        try:
            # Not a sandbox: see the module docstring.
            namespace = {
                "HookAction": HookAction,
                "datetime": datetime,
                "fnmatch": fnmatch,
                "__builtins__": {
                    "len": len,
                    "str": str,
                    "int": int,
                    "float": float,
                    "bool": bool,
                    "dict": dict,
                    "list": list,
                    "tuple": tuple,
                    "print": lambda *args: debug_logger.log_info(
                        "hook_function", self.name, " ".join(map(str, args))
                    ),
                },
            }

            exec(self.function_code, namespace)  # noqa: S102  PERMANENT(exec hook code by design)

            if "process_request" not in namespace:
                raise ValueError("Function must define 'process_request(request)'")  # noqa: TRY301  plan_M4ph1

            return namespace["process_request"]

        except Exception as e:
            debug_logger.log_error(
                "dynamic_hook",
                "compile_function",
                f"Failed to compile function for hook {self.name}: {e}",
            )
            return lambda request: HookAction(action="continue")  # noqa: ARG005  PERMANENT(interface stability)

    def matches(self, request: RequestInfo) -> bool:  # noqa: PLR0911  DEBT(F-165)
        """Check if this hook matches the request."""
        try:
            # Check URL pattern
            if "url_pattern" in self.requirements and not fnmatch.fnmatch(
                request.url, self.requirements["url_pattern"]
            ):
                return False

            # Check method
            if (
                "method" in self.requirements
                and request.method.upper() != self.requirements["method"].upper()
            ):
                return False

            # Check resource type
            if (
                "resource_type" in self.requirements
                and request.resource_type != self.requirements["resource_type"]
            ):
                return False

            # Check stage
            if (
                "stage" in self.requirements
                and request.stage != self.requirements["stage"]
            ):
                return False

            # Check custom conditions (if any)
            if "custom_condition" in self.requirements:
                condition_code = self.requirements["custom_condition"]
                # Host ``eval``, not a sandbox: see the module docstring.
                namespace = {
                    "request": request,
                    "__builtins__": {"len": len, "str": str},
                }
                try:
                    result = eval(condition_code, namespace)  # noqa: S307  PERMANENT(eval hook matching by design)
                    if not result:
                        return False
                except Exception as cond_err:
                    debug_logger.log_warning(
                        "dynamic_hook",
                        "matches",
                        f"Custom condition eval failed for hook {self.name}: "
                        f"{cond_err}",
                    )
                    return False

            return True

        except Exception as e:
            debug_logger.log_error(
                "dynamic_hook", "matches", f"Error matching hook {self.name}: {e}"
            )
            return False

    def process(self, request: RequestInfo) -> HookAction:
        """Execute the hook function."""
        try:
            self.trigger_count += 1
            self.last_triggered = datetime.now(tz=timezone.utc)

            debug_logger.log_info(
                "dynamic_hook",
                "process",
                f"Processing request {request.url} with hook {self.name}",
            )

            result = self._compiled_function(request.to_dict())

            if isinstance(result, dict):
                result = HookAction(**result)
            elif not isinstance(result, HookAction):
                debug_logger.log_error(
                    "dynamic_hook",
                    "process",
                    f"Hook {self.name} returned invalid type: {type(result)}",
                )
                return HookAction(action="continue")

            debug_logger.log_info(
                "dynamic_hook",
                "process",
                f"Hook {self.name} returned action: {result.action}",
            )
            return result

        except Exception as e:
            debug_logger.log_error(
                "dynamic_hook", "process", f"Error executing hook {self.name}: {e}"
            )
            return HookAction(action="continue")


class DynamicHookSystem:
    """Real-time dynamic hook processing system."""

    def __init__(self):
        self.hooks: dict[str, DynamicHook] = {}
        self.instance_hooks: dict[
            str, list[str]
        ] = {}  # instance_id -> list of hook_ids
        self._instance_tabs: dict[str, Any] = {}  # instance_id -> tab (for re-arming)
        self._paused_handlers: set[str] = set()  # instances with a RequestPaused hook
        self._paused_in_flight: dict[str, int] = {}  # T-1665: handlers not yet done
        # T-8944: the handler tasks themselves. asyncio keeps only a weak reference
        # to a task, so one parked on a reply that never comes was garbage
        # collected mid-await ("Task was destroyed but it is pending!").
        self._paused_tasks: dict[str, set[asyncio.Task]] = {}
        self._lock = asyncio.Lock()

    def paused_in_flight(self, instance_id: str) -> int:
        """T-1665: how many ``Fetch.requestPaused`` handlers for *instance_id* have
        started and not finished. Chrome holds each such request until its handler
        continues it, so this is the count of requests this backend is sitting on."""
        return self._paused_in_flight.get(instance_id, 0)

    async def setup_interception(self, tab, instance_id: str):
        """Set up request and response interception for a browser tab.

        Idempotent, and the ONE place Fetch interception is enabled: called once
        at spawn, then again by ``create_hook`` whenever a hook first gives this
        instance something to intercept (F-772).
        """
        try:
            self._instance_tabs[instance_id] = tab

            all_hooks = []

            instance_hook_ids = self.instance_hooks.get(instance_id, [])
            for hook_id in instance_hook_ids:
                hook = self.hooks.get(hook_id)
                if hook and hook.status == "active":
                    all_hooks.append(hook)

            for hook_id, hook in self.hooks.items():
                if (
                    hook.status == "active"
                    and hook_id not in instance_hook_ids
                    and (not hasattr(hook, "instance_ids") or not hook.instance_ids)
                ):
                    all_hooks.append(hook)

            request_patterns = []
            response_patterns = []

            for hook in all_hooks:
                url_pattern = hook.requirements.get("url_pattern", "*")
                resource_type = hook.requirements.get("resource_type")
                stage = hook.request_stage

                if stage == "response":
                    pattern = uc.cdp.fetch.RequestPattern(
                        url_pattern=url_pattern,
                        resource_type=getattr(
                            uc.cdp.network.ResourceType, resource_type.upper()
                        )
                        if resource_type
                        else None,
                        request_stage=uc.cdp.fetch.RequestStage.RESPONSE,
                    )
                    response_patterns.append(pattern)
                else:
                    pattern = uc.cdp.fetch.RequestPattern(
                        url_pattern=url_pattern,
                        resource_type=getattr(
                            uc.cdp.network.ResourceType, resource_type.upper()
                        )
                        if resource_type
                        else None,
                        request_stage=uc.cdp.fetch.RequestStage.REQUEST,
                    )
                    request_patterns.append(pattern)

            all_patterns = request_patterns + response_patterns

            if not all_patterns:
                debug_logger.log_info(
                    "dynamic_hook_system",
                    "setup_interception",
                    f"No active hooks for instance {instance_id}; leaving Fetch "
                    f"interception disabled (re-armed when a hook is created)",
                )
                return

            await tab.send(uc.cdp.fetch.enable(patterns=all_patterns))

            if instance_id not in self._paused_handlers:
                tab.add_handler(
                    uc.cdp.fetch.RequestPaused,
                    lambda event: self._spawn_paused(tab, event, instance_id),
                )
                self._paused_handlers.add(instance_id)

            debug_logger.log_info(
                "dynamic_hook_system",
                "setup_interception",
                f"Set up interception for instance {instance_id} "
                f"with {len(all_patterns)} patterns "
                f"({len(request_patterns)} request, "
                f"{len(response_patterns)} response)",
            )

        except Exception as e:
            debug_logger.log_error(
                "dynamic_hook_system",
                "setup_interception",
                f"Failed to setup interception: {e}",
            )

    def _spawn_paused(self, tab, event, instance_id: str) -> None:
        """Run one ``Fetch.requestPaused`` handler as a task that is kept alive
        until it ends and cancelled with its instance (``remove_instance``)."""
        if instance_id not in self._instance_tabs:
            # A late event for an instance already removed: nothing would cancel
            # this task, and its browser is closing.
            debug_logger.log_debug(
                "dynamic_hook_system",
                "_spawn_paused",
                f"Ignoring a paused request for removed instance {instance_id}",
            )
            return
        task = asyncio.create_task(self._on_request_paused(tab, event, instance_id))
        tasks = self._paused_tasks.setdefault(instance_id, set())
        tasks.add(task)
        task.add_done_callback(tasks.discard)

    async def _release_after_error(  # noqa: PLR0913  PERMANENT(the one fallback home for three call sites)
        self,
        tab,
        request_id: str,
        stage: str,
        method: str,
        primary: str,
        after: str,
        cause,
    ) -> None:
        """The ONE fallback after a failed paused-request step: resume the request.

        *cause* is the error that got us here. A stale interception id or a gone
        socket (:func:`gone_reason`) means there is nothing to resume, so it is
        logged as a warning and not re-sent; any other error is logged as an
        error and the request is continued so the page is not left hanging.
        """
        reason = gone_reason(cause)
        if reason:
            debug_logger.log_warning(
                "dynamic_hook_system",
                method,
                f"Not resuming {stage} {request_id}: {reason} ({cause})",
                error=cause,
            )
            return
        debug_logger.log_error("dynamic_hook_system", method, f"{primary}: {cause}")
        rid = uc.cdp.fetch.RequestId(request_id)
        try:
            await tab.send(
                uc.cdp.fetch.continue_response(request_id=rid)
                if stage == "response"
                else uc.cdp.fetch.continue_request(request_id=rid)
            )
        except Exception as fallback_err:
            reason = gone_reason(fallback_err)
            if reason:
                debug_logger.log_warning(
                    "dynamic_hook_system",
                    method,
                    f"Could not resume {stage} {request_id}: {reason} ({fallback_err})",
                    error=fallback_err,
                )
                return
            debug_logger.log_error(
                "dynamic_hook_system",
                method,
                Exception(
                    f"Failed to continue request after {after}error, "
                    f"request may be stuck: {fallback_err}"
                ),
            )

    async def _on_request_paused(self, tab, event, instance_id: str):
        """Handle intercepted requests and responses - process hooks immediately."""
        self._paused_in_flight[instance_id] = self.paused_in_flight(instance_id) + 1
        stage = "request"
        try:
            # Determine if this is request stage or response stage
            # According to nodriver docs: "The stage of the request can be determined
            # by presence of responseErrorReason and responseStatusCode -- the request
            # is at the response stage if either of these fields is present"
            is_response_stage = (
                hasattr(event, "response_status_code")
                and event.response_status_code is not None
            ) or (
                hasattr(event, "response_error_reason")
                and event.response_error_reason is not None
            )

            stage = "response" if is_response_stage else "request"

            request = RequestInfo(
                request_id=str(event.request_id),
                instance_id=instance_id,
                url=event.request.url,
                method=event.request.method,
                headers=dict(event.request.headers)
                if hasattr(event.request, "headers")
                else {},
                post_data=event.request.post_data
                if hasattr(event.request, "post_data")
                else None,
                resource_type=str(event.resource_type)
                if hasattr(event, "resource_type")
                else None,
                stage=stage,
            )

            debug_logger.log_info(
                "dynamic_hook_system",
                "_on_request_paused",
                f"Intercepted {stage}: {request.method} {request.url}",
            )

            if is_response_stage and hasattr(event, "response_status_code"):
                debug_logger.log_info(
                    "dynamic_hook_system",
                    "_on_request_paused",
                    f"Response status: {event.response_status_code}",
                )

            await self._process_request_hooks(tab, request, event)

        except Exception as e:
            await self._release_after_error(
                tab,
                str(getattr(event, "request_id", "")),
                stage,
                "_on_request_paused",
                f"Error processing {stage}",
                "",
                e,
            )
        finally:
            left = self.paused_in_flight(instance_id) - 1
            if left > 0:
                self._paused_in_flight[instance_id] = left
            else:
                self._paused_in_flight.pop(instance_id, None)

    async def _process_request_hooks(self, tab, request: RequestInfo, event=None):  # noqa: C901,PLR0912,PLR0915  DEBT(F-165)
        """Process hooks for a request/response in real-time.

        When several hooks match, the highest-priority match (lowest priority
        number) runs and lower-priority matches are shadowed - they do NOT run
        (first-match-by-priority, not a chain).
        """
        try:
            instance_hook_ids = self.instance_hooks.get(request.instance_id, [])

            matching_hooks = []
            for hook_id in instance_hook_ids:
                hook = self.hooks.get(hook_id)
                if (
                    hook
                    and hook.status == "active"
                    and hook.request_stage == request.stage
                    and hook.matches(request)
                ):
                    matching_hooks.append(hook)

            matching_hooks.sort(key=lambda h: h.priority)

            if not matching_hooks:
                debug_logger.log_info(
                    "dynamic_hook_system",
                    "_process_request_hooks",
                    f"No matching hooks for {request.stage} stage: {request.url}",
                )
                if request.stage == "response":
                    await tab.send(
                        uc.cdp.fetch.continue_response(
                            request_id=uc.cdp.fetch.RequestId(request.request_id)
                        )
                    )
                else:
                    await tab.send(
                        uc.cdp.fetch.continue_request(
                            request_id=uc.cdp.fetch.RequestId(request.request_id)
                        )
                    )
                return

            debug_logger.log_info(
                "dynamic_hook_system",
                "_process_request_hooks",
                f"Found {len(matching_hooks)} matching hooks "
                f"for {request.stage} stage: {request.url}",
            )

            response_body = None
            if request.stage == "response" and event:
                try:
                    body_result = await tab.send(
                        uc.cdp.fetch.get_response_body(
                            request_id=uc.cdp.fetch.RequestId(request.request_id)
                        )
                    )
                    response_body = body_result[0]  # body content
                    debug_logger.log_info(
                        "dynamic_hook_system",
                        "_process_request_hooks",
                        f"Retrieved response body ({len(response_body)} chars)",
                    )
                except Exception as e:
                    reason = gone_reason(e)
                    if reason:
                        debug_logger.log_warning(
                            "dynamic_hook_system",
                            "_process_request_hooks",
                            f"No response body for {request.request_id}: "
                            f"{reason} ({e})",
                            error=e,
                        )
                    else:
                        debug_logger.log_error(
                            "dynamic_hook_system",
                            "_process_request_hooks",
                            f"Failed to get response body: {e}",
                        )

            hook = matching_hooks[0]

            if len(matching_hooks) > 1:
                debug_logger.log_warning(
                    "dynamic_hook_system",
                    "_process_request_hooks",
                    f"{len(matching_hooks)} hooks matched {request.stage} "
                    f"{request.url}; only highest-priority '{hook.name}' "
                    f"(priority={hook.priority}) runs - shadowed "
                    f"(never fire): {[h.name for h in matching_hooks[1:]]}",
                )

            request_data = request.to_dict()
            if response_body:
                request_data["response_body"] = response_body
                request_data["response_status_code"] = getattr(
                    event, "response_status_code", None
                )
                response_headers = {}
                if hasattr(event, "response_headers") and event.response_headers:
                    try:
                        if isinstance(event.response_headers, dict):
                            response_headers = event.response_headers
                        elif hasattr(event.response_headers, "items"):
                            for header in event.response_headers:
                                if hasattr(header, "name") and hasattr(header, "value"):
                                    response_headers[header.name] = header.value
                        else:
                            response_headers = {}
                    except Exception as e:
                        debug_logger.log_warning(
                            "dynamic_hook_system",
                            "_process_request_hooks",
                            f"Response header normalization failed: {e}",
                        )
                        response_headers = {}
                request_data["response_headers"] = response_headers

            action = hook._compiled_function(request_data)
            if isinstance(action, dict):
                action = HookAction(**action)

            hook.trigger_count += 1
            hook.last_triggered = datetime.now(tz=timezone.utc)

            debug_logger.log_info(
                "dynamic_hook_system",
                "_process_request_hooks",
                f"Hook {hook.name} returned action: {action.action}",
            )

            await self._execute_hook_action(
                tab, request, action, event if request.stage == "response" else None
            )

        except Exception as e:
            await self._release_after_error(
                tab,
                request.request_id,
                request.stage,
                "_process_request_hooks",
                "Error processing hooks",
                "hook ",
                e,
            )

    async def create_hook(
        self,
        name: str,
        requirements: dict[str, Any],
        function_code: str,
        instance_ids: list[str] | None = None,
        priority: int = 100,
    ) -> str:
        """Create a new dynamic hook."""
        try:
            hook_id = str(uuid.uuid4())
            hook = DynamicHook(hook_id, name, requirements, function_code, priority)

            async with self._lock:
                self.hooks[hook_id] = hook

                if instance_ids:
                    for instance_id in instance_ids:
                        if instance_id not in self.instance_hooks:
                            self.instance_hooks[instance_id] = []
                        self.instance_hooks[instance_id].append(hook_id)
                else:
                    for instance_id in self.instance_hooks:
                        self.instance_hooks[instance_id].append(hook_id)

                targets = list(instance_ids or self.instance_hooks)

            # F-772: interception is armed only at spawn, and a zero-hook spawn
            # now (correctly) arms nothing. Re-arm through the SAME entry point
            # so a hook created later still intercepts.
            for instance_id in targets:
                tab = self._instance_tabs.get(instance_id)
                if tab is not None:
                    await self.setup_interception(tab, instance_id)

            debug_logger.log_info(
                "dynamic_hook_system",
                "create_hook",
                f"Created hook {name} with ID {hook_id}",
            )
            return hook_id

        except Exception as e:
            debug_logger.log_error(
                "dynamic_hook_system",
                "create_hook",
                f"Failed to create hook {name}: {e}",
            )
            raise

    def list_hooks(self) -> list[dict[str, Any]]:
        """List all hooks."""
        return [
            {
                "hook_id": hook.hook_id,
                "name": hook.name,
                "requirements": hook.requirements,
                "priority": hook.priority,
                "status": hook.status,
                "trigger_count": hook.trigger_count,
                "last_triggered": hook.last_triggered.isoformat()
                if hook.last_triggered
                else None,
                "created_at": hook.created_at.isoformat(),
            }
            for hook in self.hooks.values()
        ]

    def get_hook_details(self, hook_id: str) -> dict[str, Any] | None:
        """Get detailed hook information."""
        hook = self.hooks.get(hook_id)
        if not hook:
            return None

        return {
            "hook_id": hook.hook_id,
            "name": hook.name,
            "requirements": hook.requirements,
            "function_code": hook.function_code,
            "priority": hook.priority,
            "status": hook.status,
            "trigger_count": hook.trigger_count,
            "last_triggered": hook.last_triggered.isoformat()
            if hook.last_triggered
            else None,
            "created_at": hook.created_at.isoformat(),
        }

    async def remove_hook(self, hook_id: str) -> bool:
        """Remove a hook."""
        try:
            async with self._lock:
                if hook_id in self.hooks:
                    del self.hooks[hook_id]

                    for instance_id in self.instance_hooks:
                        if hook_id in self.instance_hooks[instance_id]:
                            self.instance_hooks[instance_id].remove(hook_id)

                    debug_logger.log_info(
                        "dynamic_hook_system", "remove_hook", f"Removed hook {hook_id}"
                    )
                    return True

            return False

        except Exception as e:
            debug_logger.log_error(
                "dynamic_hook_system",
                "remove_hook",
                f"Failed to remove hook {hook_id}: {e}",
            )
            return False

    def add_instance(self, instance_id: str):
        """Add a new browser instance."""
        if instance_id not in self.instance_hooks:
            self.instance_hooks[instance_id] = []

    def remove_instance(self, instance_id: str):
        """Remove a browser instance and its hook associations."""
        self.instance_hooks.pop(instance_id, None)
        self._instance_tabs.pop(instance_id, None)
        self._paused_handlers.discard(instance_id)
        for task in self._paused_tasks.pop(instance_id, ()):
            task.cancel()

    async def _execute_hook_action(  # noqa: C901,PLR0912  DEBT(F-165)
        self,
        tab,
        request: RequestInfo,
        action: HookAction,
        event=None,  # noqa: ARG002  PERMANENT(interface stability)
    ):
        """Execute a hook action for either request or response stage."""
        try:
            request_id = uc.cdp.fetch.RequestId(request.request_id)

            if action.action == "block":
                await tab.send(
                    uc.cdp.fetch.fail_request(
                        request_id=request_id,
                        error_reason=uc.cdp.network.ErrorReason.BLOCKED_BY_CLIENT,
                    )
                )
                debug_logger.log_info(
                    "dynamic_hook_system",
                    "_execute_hook_action",
                    f"Blocked {request.stage} {request.url}",
                )

            elif action.action == "fulfill":
                headers = []
                if action.headers:
                    for name, value in action.headers.items():
                        headers.append(uc.cdp.fetch.HeaderEntry(name=name, value=value))

                import base64

                body_bytes = (action.body or "").encode("utf-8")
                body_base64 = base64.b64encode(body_bytes).decode("ascii")

                await tab.send(
                    uc.cdp.fetch.fulfill_request(
                        request_id=request_id,
                        response_code=action.status_code or 200,
                        response_headers=headers,
                        body=body_base64,
                    )
                )
                debug_logger.log_info(
                    "dynamic_hook_system",
                    "_execute_hook_action",
                    f"Fulfilled {request.stage} {request.url}",
                )

            elif action.action == "redirect" and request.stage == "request":
                await tab.send(
                    uc.cdp.fetch.continue_request(request_id=request_id, url=action.url)
                )
                debug_logger.log_info(
                    "dynamic_hook_system",
                    "_execute_hook_action",
                    f"Redirected request {request.url} to {action.url}",
                )

            elif action.action == "modify":
                if request.stage == "response":
                    response_headers = []
                    if action.headers:
                        for name, value in action.headers.items():
                            response_headers.append(
                                uc.cdp.fetch.HeaderEntry(name=name, value=value)
                            )

                    await tab.send(
                        uc.cdp.fetch.continue_response(
                            request_id=request_id,
                            response_code=action.status_code,
                            response_headers=response_headers or None,
                        )
                    )
                    debug_logger.log_info(
                        "dynamic_hook_system",
                        "_execute_hook_action",
                        f"Modified response for {request.url}",
                    )
                else:
                    headers = []
                    if action.headers:
                        for name, value in action.headers.items():
                            headers.append(
                                uc.cdp.fetch.HeaderEntry(name=name, value=value)
                            )

                    await tab.send(
                        uc.cdp.fetch.continue_request(
                            request_id=request_id,
                            url=action.url or request.url,
                            method=action.method or request.method,
                            headers=headers or None,
                            post_data=action.post_data,
                        )
                    )
                    debug_logger.log_info(
                        "dynamic_hook_system",
                        "_execute_hook_action",
                        f"Modified request {request.url}",
                    )

            elif request.stage == "response":
                await tab.send(uc.cdp.fetch.continue_response(request_id=request_id))
                debug_logger.log_info(
                    "dynamic_hook_system",
                    "_execute_hook_action",
                    f"Continued response {request.url}",
                )
            else:
                await tab.send(uc.cdp.fetch.continue_request(request_id=request_id))
                debug_logger.log_info(
                    "dynamic_hook_system",
                    "_execute_hook_action",
                    f"Continued request {request.url}",
                )

        except Exception as e:
            await self._release_after_error(
                tab,
                request.request_id,
                request.stage,
                "_execute_hook_action",
                f"Error executing {request.stage} action",
                "action ",
                e,
            )


dynamic_hook_system = DynamicHookSystem()
